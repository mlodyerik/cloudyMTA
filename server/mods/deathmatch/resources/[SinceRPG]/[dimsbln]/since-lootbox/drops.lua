limitToBan = {}
function formatLimitsToBan()
    for i,vv in pairs(boxList) do
        for k, v in ipairs(vv.items) do
            if type(v.value) == 'table' then
                local formatedName = v.name
                if not limitToBan[formatedName] then
                    limitToBan[formatedName] = v.value.max
                end
                if limitToBan[formatedName] < v.value.max then
                    limitToBan[formatedName] = v.value.max
                end
            end
        end
    end
end

