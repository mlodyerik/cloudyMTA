function getItemByRarityNumber(items, percent)
    local totalRareLevel = 0

    for _, item in ipairs(items) do
        totalRareLevel = totalRareLevel + (item.rareLevel or 0)
    end

    for _, item in ipairs(items) do
        if math.random(0, 100) <= item.chance then
            return item
        end
    end

    return items[math.random(1, #items)]
end

