function setVehicleDesc(veh, text)
    local upgrades = getElementData(veh, "vehicle:upgrades") or {}
    upgrades['vopis'] = true
    upgrades['vopis:text'] = text
    setElementData(veh, "vehicle:upgrades", upgrades)
end


function addCommas(n)
    local left,num,right = string.match(n,'^([^%d]*%d)(%d*)(.-)$')
    return left..(num:reverse():gsub('(%d%d%d)','%1,'):reverse())..right
end

function createVehicles()
    for i, v in ipairs(vehicles) do
        local baseModel, isCustom = exports['since-custommodels']:checkModelID(v.data.model, 'vehicle')
        local veh = nil
        if isCustom then
            veh = createVehicle(baseModel, unpack(v.pos))
            setElementData(veh, 'baseID', baseModel)
            setElementData(veh, 'vehicleID', v.data.model)
        else
            veh = createVehicle(v.data.model, unpack(v.pos))
        end

        local modelName = v.data.sport and exports['since-vehiclenames']:getVehicleName(v.data.model)..' Sport' or exports['since-vehiclenames']:getVehicleName(v.data.model)
        setVehicleDesc(veh, '#4f9bff'..modelName..'#ffffff\nCena: #7dff7d'..addCommas(v.data.cost)..' $#ffffff\n#d6d6d6(Podejdź do pojazdu aby uzyskać więcej informacji)')

        setElementFrozen(veh, true)
        setVehicleLocked(veh, true)
        setVehicleColor(veh, 255, 255, 255, 255, 255, 255)
        setVehicleVariant(veh, v.data.variant[1], v.data.variant[2])
        setElementData(veh, "vehicle:variant", v.data.variant)

        setElementInterior(veh, v.int)
        setElementDimension(veh, v.dim)

        local shape = createColSphere(v.pos[1], v.pos[2], v.pos[3], getVehicleType(veh) == 'Boat' and 5 or 3)
        setElementInterior(shape, v.int)
        setElementDimension(shape, v.dim)
        setElementData(shape, "vehicle:dealer:data", v.data)
        setElementData(shape, "vehicle:dealer:intdim", {v.int, v.dim})
        setElementData(shape, "vehicle:dealer:veh", veh)

        attachElements(shape, veh, 0, 0, 0, 0, 0, 0)
    end
end
addEventHandler('onResourceStart', resourceRoot, createVehicles)