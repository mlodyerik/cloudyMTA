function calculatePercentages(boxList)
    for boxName, boxData in pairs(boxList) do
        local items = boxData.items
        local totalRareLevel = 0

        for _, item in ipairs(items) do
            totalRareLevel = totalRareLevel + (item.rareLevel or 0)
        end

        for _, item in ipairs(items) do
            local rarePercentage = calculatePercentage(totalRareLevel, item.rareLevel or 0)
            item.chance = rarePercentage
        end
    end
end

function calculatePercentage(totalRareLevel, itemRareLevel)
    local percentage = (itemRareLevel / totalRareLevel) * 100
    
    return percentage
end

calculatePercentages(boxList)

function formatNumber(amount) 
    local formatted = amount 
    while true do   
        formatted, k = string.gsub(formatted, '^(-?%d+)(%d%d%d)', '%1 %2') 
        if (k==0) then 
            break 
        end 
    end 

    return formatted 
end

function RGBTOHEX(r, g, b)
    return string.format("#%.2X%.2X%.2X", r, g, b)
end

function getColorFromPercent(percent)
    if percent > 75 then
        return 125, 175, 255
    elseif percent > 45 then
        return 177, 105, 255
    elseif percent > 25 then
        return 242, 61, 255
    elseif percent > 5 then
        return 255, 25, 25
    elseif percent > 0 then
        return 255, 255, 0
    end
end

function getRareName(percent)
    if percent > 75 then
        return 'Zwykły'
    elseif percent > 45 then
        return 'Rzadki'
    elseif percent > 25 then
        return 'Bardzo rzadki'
    elseif percent > 5 then
        return 'Legendarny'
    elseif percent > 0 then
        return 'Unikalny'
    end
end

function getBoxDrops(boxName)
    local items = boxList[boxName].items
    local drops = {}
    local value = nil

    for i, item in ipairs(items) do
        if item.name == 'Pojazd' then
            value = exports['since-vehiclenames']:getVehicleName(item.value)
        elseif item.name == 'Gotówka' then
            if type(item.value) == 'table' then
                value = '$ '..formatNumber(item.value.min)..' - $ '..formatNumber(item.value.max)
            else
                value = '$ '..formatNumber(item.value)
            end
        elseif item.name == 'SRP' then
            if type(item.value) == 'table' then
                value = item.value.min..' - '..item.value.max..' SRP'
            else
                value = item.value..' SRP'
            end
        elseif item.name == 'Punkty Premium' then
            if type(item.value) == 'table' then
                value = item.value.min..' - '..item.value.max..' PP'
            else
                value = item.value..' PP'
            end
        elseif item.name == 'wPLN' then
            if type(item.value) == 'table' then
                value = item.value.min..' - '..item.value.max..' wPLN'
            else
                value = item.value..' wPLN'
            end
        end

        local color = RGBTOHEX(getColorFromPercent(item.rareLevel))
        local rareName = getRareName(item.chance)
        local chance = string.format("%.2f", item.chance)
        table.insert(drops, i..'. #2E756F'..item.name..'#ffffff ('..value..') - '..color..'('..rareName..'): ' .. chance..' %#ffffff')
    end

    return drops
end

