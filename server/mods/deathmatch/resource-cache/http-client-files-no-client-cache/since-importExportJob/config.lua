function findIndex(tbl, value)
    for i,v in ipairs(tbl) do
        if v[1] == value then
            return i,v
        end
    end
    return false
end

function formatNumber(n)
    n = tonumber(n)
    if not n then return '0' end
    local left,num,right = string.match(n,'^([^%d]*%d)(%d*)(.-)$')
    return left..(num:reverse():gsub('(%d%d%d)','%1,'):reverse())..right
end

